package com.katya.app.tts

/**
 * Аудиофокус на десктопе.
 *
 * Правило, ради которого существует весь этот класс, — «включить музыку обратно
 * только если она играла до нас» — на десктопе невыполнимо: у AWT нет API
 * запроса фокуса, и единственный способ узнать, играет ли сейчас что-то, —
 * посмотреть на чужой процесс. Это неприемлемо.
 *
 * Поэтому здесь не делается ничего. Альтернатива — слать медиаклавиши вслепую
 * (Robot), но она нажимала бы «пауза» пользователю, у которого ничего не
 * играет, и «продолжить» тому, кто слушает подкаст: ровно то поломанное
 * поведение, от которого этот класс и был написан.
 *
 * Последствие честное: музыка не ставится на паузу во время озвучки. Сказать
 * пользователю об этом нужно в интерфейсе, а не прятать.
 */
actual object AudioFocusController {

    actual fun acquire() {
        // Захватывать фокус нечем: AWT такого API не предоставляет.
    }

    actual fun release() {
        // Возвращать нечего — см. выше.
    }
}
