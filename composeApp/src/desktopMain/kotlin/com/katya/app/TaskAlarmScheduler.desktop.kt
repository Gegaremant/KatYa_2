package com.katya.app

import com.katya.app.tools.AppLogger

/**
 * Будильник для задач на десктопе — заглушка.
 *
 * На Android `TaskAlarmScheduler` поднимает процесс по AlarmManager, и задачи
 * срабатывают при закрытом приложении. На десктопе экран не засыпает, но окно
 * закрывается, а вместе с ним и планировщик — тогда задача не сработает вовсе.
 *
 * Сделать по-настоящему можно было бы через `systemd --user` или планировщик ОС,
 * но это отдельная подсистема с двумя реализациями на разные системы, и
 * выдавать за неё пустую заглушку нельзя. Пока честно: задачи выполняются, пока
 * приложение открыто, и карточка задачи на десктопе это говорит.
 */
actual fun createTaskAlarmScheduler(): TaskAlarmScheduler = object : TaskAlarmScheduler {
    override fun scheduleNext() {
        AppLogger.d("Задачи", "на десктопе выполняются, пока приложение открыто")
    }

    override fun cancel() {
        // Будильника нет — отменять нечего.
    }
}
