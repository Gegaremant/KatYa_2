package com.katya.app.audio

import org.koin.core.module.Module
import org.koin.dsl.module

/**
 * Модуль аудиозахвата на десктопе пуст.
 *
 * На Android здесь `AudioRecord`: он пишет микрофон для распознавания речи.
 * На десктопе микрофон есть, но отдельный захват не нужен — озвучка идёт через
 * системный синтезатор, а распознавание речи на этой платформе не подключено
 * (см. `sttModule`).
 *
 * Модуль остаётся, потому что `Main.kt` подставляет его по ссылке: пустой
 * `module {}` означает «здесь ничего не регистрируется», а отсутствие — падение
 * на старте.
 */
actual val audioModule: Module = module { }
