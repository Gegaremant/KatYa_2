package com.katya.app.data

/**
 * Разделение памяти по личностям (вариант 3 из обсуждения).
 *
 * Знание бывает общим — «достаточно ключ» — или личным для одной роли: то, что
 * человек сказал Подруге, Коллеге не обязано быть известно. Поэтому запись
 * адресуется парой «ключ + роль», а не одним ключом.
 *
 * ## Почему роль едет в ключе, а не в отдельном столбце
 *
 * Естественное решение — колонка `role` и составной первичный ключ. Здесь оно
 * невозможно, и это не каприх:
 *
 * `composeApp/build.gradle.kts` включает `verifyMigrations`, и в этой сборке
 * верификация применяет миграции к **пустой** базе. Поэтому любая миграция,
 * трогающая уже существующую таблицу, падает проверку с «No table found» —
 * проверено пробой на `ALTER TABLE conversationEntity ADD COLUMN`, ровно так же.
 *
 * Значит таблицу `memoryEntry` нельзя пересоздать, а столбец добавить нельзя.
 * Ключ — единственное поле, где различие уже выражается, и он для этого
 * предназначен: уникальность и есть то, что нужно обеспечить раздельно по
 * ролям.
 *
 * Префикс короткий и нечитаемый человеком, потому что наружу ключ не
 * показывается — модель задаёт смысловой ключ, кодирование занимает хранилище.
 *
 * Существующие записи префикса не имеют и читаются как общие: набраны до
 * разделения, принадлежат пользователю целиком, а не одной из личностей.
 */
internal object RoleScopedMemoryKey {
    /**
     * Намеренно не похож на то, что модель сгенерирует сама: она пишет
     * человекочитаемые ключи вроде `любимый_цвет`, и такой префикс среди них не
     * встречается. Разбор идёт по первому вхождению двоеточия, поэтому ключ,
     * содержащий двоеточие дальше, остаётся целым.
     */
    const val PREFIX = "katya-role:"

    /** Ключ в том виде, в котором он лежит в базе. */
    fun encode(key: String, role: String?): String = if (role.isNullOrBlank()) key else PREFIX + role + ":" + key

    /** Роль и исходный ключ из записи в базе. */
    fun decode(storedKey: String): Pair<String?, String> {
        if (!storedKey.startsWith(PREFIX)) return null to storedKey
        val rest = storedKey.removePrefix(PREFIX)
        val separator = rest.indexOf(':')
        // Префикс есть, а разделителя роли нет — запись обрезана или подделана.
        // Всё после префикса отдаём как ключ: терять содержимое из-за испорченного
        // префикса хуже, чем показать пользователю ключ вместе со служебным хвостом.
        if (separator <= 0) return null to rest
        return rest.substring(0, separator) to rest.substring(separator + 1)
    }

    /** Видно ли запись личности [role], если читает кто-то с ролью [viewer]. */
    fun isVisibleTo(storedKey: String, viewer: String?): Boolean {
        val (owner, _) = decode(storedKey)
        return owner == null || owner == viewer
    }
}
